# -*- coding: utf-8 -*-
"""Заглавная тема: бальная мазурка. Своя, в приёмах жанра.

Приёмы (их и берём): быстрые три четверти, бас октавами на «раз»,
аккорды на «два» и «три», акцент на вторую долю, триольная раскачка в
мелодии, четырёхтактовая фанфара перед темой, хроматический ход во
внутреннем голосе. Мелодия и гармония — свои.
"""
N={'C':0,'C#':1,'Db':1,'D':2,'D#':3,'Eb':3,'E':4,'F':5,'F#':6,'Gb':6,'G':7,
   'G#':8,'Ab':8,'A':9,'A#':10,'Bb':10,'B':11}
def m(s):
    i=1
    while s[i] in '#b': i+=1
    return 12*(int(s[i:])+1)+N[s[:i]]
CH={'':[0,4,7],'m':[0,3,7],'7':[0,4,7,10],'dim':[0,3,6],'m7':[0,3,7,10],'maj7':[0,4,7,11]}
def chord(name, oct=3):
    i=1
    while i<len(name) and name[i] in '#b': i+=1
    root, q = name[:i], name[i:]
    return [12*(oct+1)+N[root]+s for s in CH[q]]

BEATS=3
out=[]
def put(beat, pitch, dur, vel):
    out.append([round(beat,3), pitch if isinstance(pitch,int) else m(pitch), round(dur,3), int(vel)])

# ---- гармония по тактам (24 такта) --------------------------------
HARM = (['Cm','Bdim','Bb','Bb']            # фанфара
      + ['Cm','G','Cm','Fm','Cm','G','Cm','Cm']     # тема A
      + ['Ab','Eb','Ab','Fm','Cm','G','Cm','G']     # тема B
      + ['Cm','Fm','G','Cm'])                        # возврат
BARS=len(HARM)

# ---- фанфара: полные аккорды вниз, как распахнутая дверь в зал -----
for b,(nm,vel) in enumerate(zip(HARM[:4],(84,76,84,70))):
    c=chord(nm,2); top=chord(nm,4)[:2]        # верх только двумя нотами
    t=b*BEATS
    for k,p in enumerate(c+top): put(t+k*0.012, p, 1.2, vel-k*3)
    if b<3:
        for k,p in enumerate(chord(nm,3)): put(t+2+k*0.012, p, .55, vel-14-k*3)

# ---- аккомпанемент темы: бас октавами на «раз», аккорды на «два-три»
for b in range(4,BARS):
    nm=HARM[b]; t=b*BEATS
    root=chord(nm,1)[0]
    put(t,        root,    .85, 92)                 # бас
    put(t+0.008,  root+12, .85, 84)                 # и его октава
    for k,p in enumerate(chord(nm,3)):
        put(t+1+k*0.010, p, .55, 74)                # «два» — акцент мазурки
    for k,p in enumerate(chord(nm,3)):
        put(t+2+k*0.010, p, .50, 58)                # «три» — легче

# ---- мелодия: (такт, доля, нота, длительность) ---------------------
MEL = [
  # тема A — поднимается и падает обратно, с триольной раскачкой
  (4,0,'G4',1),(4,1,'C5',.67),(4,1.67,'D5',.33),(4,2,'Eb5',1),
  (5,0,'D5',1),(5,1,'C5',.67),(5,1.67,'B4',.33),(5,2,'C5',1),
  (6,0,'G5',1),(6,1,'F5',.67),(6,1.67,'Eb5',.33),(6,2,'D5',1),
  (7,0,'C5',1.5),(7,1.5,'Ab4',.5),(7,2,'C5',1),
  (8,0,'G4',1),(8,1,'C5',.67),(8,1.67,'Eb5',.33),(8,2,'G5',1),
  (9,0,'F5',1),(9,1,'Eb5',.67),(9,1.67,'D5',.33),(9,2,'C5',1),
  (10,0,'D5',1),(10,1,'Eb5',.67),(10,1.67,'F5',.33),(10,2,'G5',1),
  (11,0,'C5',2.4),
  # тема B — шире и выше, потом вниз к доминанте
  (12,0,'Eb5',1),(12,1,'G5',.67),(12,1.67,'Ab5',.33),(12,2,'C6',1),
  (13,0,'Bb5',1),(13,1,'G5',.67),(13,1.67,'Eb5',.33),(13,2,'G5',1),
  (14,0,'Ab5',1),(14,1,'C6',.67),(14,1.67,'Bb5',.33),(14,2,'Ab5',1),
  (15,0,'G5',1.5),(15,1.5,'F5',.5),(15,2,'Ab5',1),
  (16,0,'G5',1),(16,1,'Eb5',.67),(16,1.67,'C5',.33),(16,2,'G4',1),
  (17,0,'Ab4',1),(17,1,'B4',.67),(17,1.67,'D5',.33),(17,2,'F5',1),
  (18,0,'Eb5',1),(18,1,'D5',.67),(18,1.67,'C5',.33),(18,2,'B4',1),
  (19,0,'D5',1.5),(19,1.5,'G4',.5),(19,2,'B4',1),
  # возврат
  (20,0,'C5',1),(20,1,'Eb5',.67),(20,1.67,'G5',.33),(20,2,'C6',1),
  (21,0,'Ab5',1),(21,1,'F5',.67),(21,1.67,'Eb5',.33),(21,2,'C5',1),
  (22,0,'D5',1),(22,1,'F5',.67),(22,1.67,'Ab5',.33),(22,2,'B5',1),
  (23,0,'C6',2.5),
]
for (bar,beat,note,dur) in MEL:
    t=bar*BEATS+beat
    acc = 100 if beat==0 else (94 if beat==1 else 88)   # вторая доля почти как первая
    if dur<=.4: acc-=8
    put(t-0.006, note, dur, acc)

out.sort(key=lambda x:x[0])
loop=BARS*BEATS
print(f'// intro: своя мазурка, {BARS} тактов, {len(out)} нот, петля {loop} долей')
print(f'      loopBeats:{loop}, perf:[')
line='        '
for it in out:
    s='['+','.join(f'{v:g}' for v in it)+'],'
    if len(line)+len(s)>96: print(line); line='        '
    line+=s
if line.strip(): print(line.rstrip(','))
print('      ],')
