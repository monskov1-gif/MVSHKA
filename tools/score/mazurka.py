# -*- coding: utf-8 -*-
"""Заглавная тема: своя мазурка. Строение задано заказчиком:

    1. резкие ноты в начале, между ними паузы      (такты 1–4)
    2. весёлая мелодия средней скорости            (такты 5–16)
    3. быстрая игра нотами, чтобы запомнилось      (такты 17–24)
    4. короткий возврат резких нот — замкнуть круг (такты 25–26)

Первая попытка звучала кабаком: быстрый ум-па-па с ударом на каждую
долю и один рояль в среднем регистре. Поэтому здесь: аккомпанемент
только на «два», бас не в каждом такте, и три инструмента вместо
одного — струнные ведут, рояль играет пробеги, контрабас держит низ.

Приёмы жанра (три четверти, акцент на вторую долю, триольная раскачка)
сняты с мазурки из «Маскарада» Хачатуряна. Приёмы не охраняются; сама
вещь охраняется до 2048 года, поэтому ноты здесь свои.
"""
N={'C':0,'C#':1,'Db':1,'D':2,'D#':3,'Eb':3,'E':4,'F':5,'F#':6,'Gb':6,'G':7,
   'G#':8,'Ab':8,'A':9,'A#':10,'Bb':10,'B':11}
def m(s):
    i=1
    while s[i] in '#b': i+=1
    return 12*(int(s[i:])+1)+N[s[:i]]
CH={'':[0,4,7],'m':[0,3,7],'7':[0,4,7,10],'dim':[0,3,6],'dim7':[0,3,6,9],
    'm7':[0,3,7,10],'maj7':[0,4,7,11],'7b9':[0,4,7,10,13],'6':[0,4,7,9]}
def chord(name, oct=3):
    i=1
    while i<len(name) and name[i] in '#b': i+=1
    root,q=name[:i],name[i:]
    return [12*(oct+1)+N[root]+s for s in CH[q]]
SC = {  # лады для пробегов: ступени от тоники
  'Cm':  [0,2,3,5,7,8,11], 'Fm':[0,2,3,5,7,8,10], 'G7b9':[0,1,3,4,6,7,9,10],
  'Ab':  [0,2,4,5,7,9,11], 'Eb':[0,2,4,5,7,9,11], 'Bb':[0,2,4,5,7,9,10],
}
BEATS=3
out=[]
def put(beat, pitch, dur, vel, ins=None, pan=None):
    p = pitch if isinstance(pitch,int) else m(pitch)
    row=[round(beat,3), p, round(dur,3), int(max(1,min(127,vel)))]
    if ins or pan is not None:
        row.append(ins or 'piano')
        if pan is not None: row.append(round(pan,2))
    out.append(row)

HARM = (['Cm','Cm','Ab','G7b9']
      + ['Cm','Cm','Fm','G7b9','Cm','Ab','Fm','G7b9']
      + ['Eb','Bb','Eb','Cm','Ab','Fm','G7b9','Cm']
      + ['Cm','Fm','G7b9','Cm','Ab','G7b9','Cm','Cm']
      + ['Cm','G7b9'])
BARS=len(HARM)

# ---- 1. РЕЗКИЕ НОТЫ С ПАУЗАМИ -------------------------------------
#    Удар — тишина — удар. Пауза здесь работает не меньше самой ноты:
#    зал замолкает, и только потом начинается танец.
HITS = [(0,0,'Cm',104),(0,2,'Cm',86),(1,1,'Cm',96),
        (2,0,'Ab',100),(2,2,'Ab',84),(3,1,'G7b9',108)]
for (bar,beat,nm,vel) in HITS:
    t=bar*BEATS+beat
    for k,p in enumerate(chord(nm,2)): put(t+k*0.012, p, .34, vel-k*4, 'strings', -0.22)
    for k,p in enumerate(chord(nm,3)): put(t+0.02+k*0.012, p, .30, vel-16-k*4, 'strings', 0.22)
    put(t, chord(nm,1)[0], .40, vel-6, 'bass', -0.1)

# ---- аккомпанемент темы: бас на «раз», аккорд на «два» -------------
for b in range(4, 28):
    nm=HARM[b]; t=b*BEATS
    heavy=(b-4)%4==0
    put(t, chord(nm,1)[0], 2.0, 70 if heavy else 54, 'bass', -0.12)
    for k,p in enumerate(chord(nm,3)):
        put(t+1+k*0.014, p, .70, 48-k*3, 'piano', -0.34)
    if (b-4)%2==1:
        for k,p in enumerate(chord(nm,3)[:2]):
            put(t+2+k*0.014, p, .52, 36-k*3, 'piano', -0.34)

# ---- 2. МЕЛОДИЯ СРЕДНЕЙ СКОРОСТИ ----------------------------------
#    Идёт четвертями и восьмыми, с мазурочной оттяжкой на вторую долю.
#    В тактах 12–15 уходит в ми-бемоль мажор — отсюда и «весело», но
#    из минора, а не вместо него.
MEL = [
  (4,0,'G4',1),(4,1,'C5',.67),(4,1.67,'D5',.33),(4,2,'Eb5',1),
  (5,0,'D5',1),(5,1,'C5',.67),(5,1.67,'B4',.33),(5,2,'C5',1),
  (6,0,'F5',1),(6,1,'Eb5',.67),(6,1.67,'D5',.33),(6,2,'C5',1),
  (7,0,'B4',1.5),(7,1.5,'D5',.5),(7,2,'G4',1),
  (8,0,'G4',1),(8,1,'C5',.67),(8,1.67,'Eb5',.33),(8,2,'G5',1),
  (9,0,'Ab5',1),(9,1,'G5',.67),(9,1.67,'F5',.33),(9,2,'Eb5',1),
  (10,0,'F5',1),(10,1,'Ab5',.67),(10,1.67,'G5',.33),(10,2,'F5',1),
  (11,0,'G5',2.4),
  (12,0,'Bb4',1),(12,1,'Eb5',.67),(12,1.67,'F5',.33),(12,2,'G5',1),
  (13,0,'F5',1),(13,1,'D5',.67),(13,1.67,'Bb4',.33),(13,2,'D5',1),
  (14,0,'Eb5',1),(14,1,'G5',.67),(14,1.67,'Bb5',.33),(14,2,'G5',1),
  (15,0,'Eb5',1.5),(15,1.5,'C5',.5),(15,2,'Eb5',1),
  (16,0,'Ab5',1),(16,1,'G5',.67),(16,1.67,'F5',.33),(16,2,'Eb5',1),
  (17,0,'F5',1),(17,1,'Eb5',.67),(17,1.67,'D5',.33),(17,2,'B4',1),
  (18,0,'D5',1.5),(18,1.5,'F5',.5),(18,2,'Ab5',1),
  (19,0,'G5',2.4),
]
for (bar,beat,note,dur) in MEL:
    t=bar*BEATS+beat
    vel = 84 if beat==0 else (80 if beat==1 else 74)   # вторая доля почти как первая
    if dur<=.4: vel-=8
    put(t-0.008, note, dur, vel, 'strings', 0.3)
    if dur>=2: put(t+0.02, m(note)-12, dur*.8, vel-36, 'piano', 0.05)

# ---- 3. БЫСТРАЯ ИГРА НОТАМИ ---------------------------------------
#    Шестнадцатые по ладу такта: вверх, вниз и снова вверх. Играет
#    рояль — это пианистическая фактура, струнные под ней держат.
def run(bar, low, shape):
    """shape: список (доля, длина в шестнадцатых, направление, старт-ступень)"""
    nm=HARM[bar]; base=m(low)
    sc=SC.get(nm, SC['Cm']); root=chord(nm,1)[0]%12
    deg=lambda i: base + (root - base%12)%12 + 12*(i//len(sc)) + sc[i%len(sc)]
    t0=bar*BEATS
    for (beat, count, dirn, start) in shape:
        for k in range(count):
            i = start + (k if dirn>0 else -k)
            put(t0+beat+k*0.25, deg(i), .22, 76 - (k%4)*5 + (6 if k%4==0 else 0),
                'piano', 0.12)
for b,(shape) in zip(range(20,28), [
      [(0,4,1,0),(1,4,1,4),(2,4,1,8)],
      [(0,4,1,11),(1,4,-1,11),(2,4,-1,7)],
      [(0,4,1,3),(1,4,1,7),(2,4,1,11)],
      [(0,4,-1,13),(1,4,-1,9),(2,4,-1,5)],
      [(0,4,1,2),(1,4,1,6),(2,4,1,10)],
      [(0,4,-1,12),(1,4,-1,8),(2,2,-1,4)],
      [(0,4,1,0),(1,4,1,4),(2,4,1,8)],
      [(0,4,1,11),(1,2,1,15),(2,1,1,17)],
  ]):
    run(b, 'C4', shape)
    nm=HARM[b]
    for k,p in enumerate(chord(nm,3)):                  # струнные держат гармонию
        put(b*BEATS+k*0.02, p, 2.8, 40-k*4, 'strings', -0.3)

# ---- 4. ВОЗВРАТ РЕЗКИХ НОТ: круг замыкается -----------------------
for (bar,beat,nm,vel) in [(28,0,'Cm',104),(28,2,'Cm',88),(29,1,'G7b9',110)]:
    t=bar*BEATS+beat
    for k,p in enumerate(chord(nm,2)): put(t+k*0.012, p, .34, vel-k*4, 'strings', -0.22)
    for k,p in enumerate(chord(nm,3)): put(t+0.02+k*0.012, p, .30, vel-16-k*4, 'strings', 0.22)
    put(t, chord(nm,1)[0], .40, vel-6, 'bass', -0.1)

out.sort(key=lambda x:x[0])
loop=BARS*BEATS
print(f'// intro: своя мазурка, {BARS} тактов, {len(out)} нот, петля {loop} долей')
print(f'      loopBeats:{loop}, perf:[')
line='        '
for it in out:
    s='['+','.join((f"'{v}'" if isinstance(v,str) else f'{v:g}') for v in it)+'],'
    if len(line)+len(s)>96: print(line); line='        '
    line+=s
if line.strip(): print(line.rstrip(','))
print('      ],')
